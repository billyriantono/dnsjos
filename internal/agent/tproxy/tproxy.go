// Package tproxy installs the node-level DNS redirect that feeds dnsdist when
// ConfigSpec.Listen.TProxy is enabled (SPEC §6.14). dnsdist cannot open IP_TRANSPARENT
// sockets, so the agent uses an nftables REDIRECT into a dedicated dnsdist listener:
// redirected packets keep their client source address, and dnsdist's ACL, abuse limits
// and analytics work exactly as for directly connected clients.
package tproxy

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"log/slog"
	"net/netip"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"

	"github.com/billyriantono/dnsjos/internal/shared/api"
)

// Paths owned by this package (root-prefixed in tests).
const (
	NFTFile       = "/var/lib/dnsjos/dnsjos-tproxy.nft"
	ScriptPath    = "/usr/local/lib/dnsjos/tproxy-apply.sh"
	CleanupPath   = "/usr/local/lib/dnsjos/tproxy-cleanup.sh"
	UnitPath      = "/etc/systemd/system/dnsjos-tproxy.service"
	UnitName      = "dnsjos-tproxy.service"
	RelayUnitPath = "/etc/systemd/system/dnsjos-tproxy-relay.service"
	RelayUnitName = "dnsjos-tproxy-relay.service"
	// AgentBinary is the installed agent; the relay unit runs it as root so it can open
	// IP_TRANSPARENT sockets.
	AgentBinary = "/usr/local/bin/dnsjos-agent"
	// mark/table separate our policy routing from a core router's FBF rules.
	tproxyMark  = "0x5315"
	tproxyTable = "5315"
	tproxyPrio  = "100"
)

const tableName = "dnsjos_tproxy"

// Files is the rendered redirect configuration.
type Files struct {
	NFT       []byte
	Script    []byte
	Cleanup   []byte
	Unit      []byte
	RelayUnit []byte
}

// Render returns the nftables rules for spec.Listen.TProxy. It returns an empty Files
// when the feature is disabled.
func Render(spec api.ConfigSpec) (Files, error) {
	tp := spec.Listen.TProxy
	if !tp.Enabled {
		return Files{}, nil
	}
	port := tp.EffectivePort()
	tproxy := tp.IsTProxy()

	exclude4, exclude6 := []string{}, []string{}
	// Only explicit exclusions: the chain hooks prerouting, so dnsdist's own upstream
	// queries (locally generated, OUTPUT/POSTROUTING) never reach it. Excluding upstream
	// addresses here would let clients bypass the redirect by querying them directly.
	for _, c := range tp.ExcludeDst {
		p, err := parsePrefix(c)
		if err != nil {
			return Files{}, fmt.Errorf("tproxy: exclude_dst: %w", err)
		}
		if p.Addr().Is4() {
			exclude4 = append(exclude4, p.String())
		} else {
			exclude6 = append(exclude6, p.String())
		}
	}
	source4, source6 := []string{}, []string{}
	for _, c := range tp.Sources {
		p, err := parsePrefix(c)
		if err != nil {
			return Files{}, fmt.Errorf("tproxy: sources: %w", err)
		}
		if p.Addr().Is4() {
			source4 = append(source4, p.String())
		} else {
			source6 = append(source6, p.String())
		}
	}

	sortUnique := func(s []string) []string {
		slices.Sort(s)
		return slices.Compact(s)
	}
	exclude4, exclude6 = sortUnique(exclude4), sortUnique(exclude6)
	source4, source6 = sortUnique(source4), sortUnique(source6)

	var b strings.Builder
	b.WriteString("# generated by dnsjos: DNS redirect (TProxy mode), do not edit\n")
	fmt.Fprintf(&b, "table inet %s {\n", tableName)
	set := func(name, typ string, elements []string) {
		fmt.Fprintf(&b, "\tset %s {\n\t\ttype %s\n\t\tflags interval\n", name, typ)
		if len(elements) > 0 {
			fmt.Fprintf(&b, "\t\telements = { %s }\n", strings.Join(elements, ", "))
		}
		b.WriteString("\t}\n")
	}
	set("exclude4", "ipv4_addr", exclude4)
	set("exclude6", "ipv6_addr", exclude6)
	set("source4", "ipv4_addr", source4)
	set("source6", "ipv6_addr", source6)
	if len(tp.Interfaces) > 0 {
		quoted := make([]string, len(tp.Interfaces))
		for i, name := range tp.Interfaces {
			quoted[i] = fmt.Sprintf("%q", name)
		}
		fmt.Fprintf(&b, "\tset ifaces {\n\t\ttype ifname\n\t\telements = { %s }\n\t}\n", strings.Join(quoted, ", "))
	}

	b.WriteString("\tchain prerouting {\n")
	if tproxy {
		b.WriteString("\t\ttype filter hook prerouting priority mangle; policy accept;\n")
	} else {
		b.WriteString("\t\ttype nat hook prerouting priority dstnat; policy accept;\n")
	}
	b.WriteString("\t\tiifname \"lo\" return\n")
	if tproxy {
		// Direct queries to the node's own addresses stay with dnsdist on port 53;
		// the relay's reply socket binds the original destination and would collide
		// with that listener.
		b.WriteString("\t\tfib daddr type local return\n")
	}
	b.WriteString("\t\tip daddr @exclude4 return\n")
	b.WriteString("\t\tip6 daddr @exclude6 return\n")
	if len(source4) > 0 || len(source6) > 0 {
		// A source list restricts both families: listing only IPv4 means IPv6 traffic is
		// not intercepted, which is what an operator who named IPv4 networks expects.
		b.WriteString("\t\tip saddr != @source4 return\n")
		b.WriteString("\t\tip6 saddr != @source6 return\n")
	}
	if len(tp.Interfaces) > 0 {
		b.WriteString("\t\tiifname != @ifaces return\n")
	}
	if tproxy {
		fmt.Fprintf(&b, "\t\tmeta nfproto ipv4 meta l4proto { tcp, udp } th dport 53 tproxy ip to :%d meta mark set %s accept\n", port, tproxyMark)
		fmt.Fprintf(&b, "\t\tmeta nfproto ipv6 meta l4proto { tcp, udp } th dport 53 tproxy ip6 to :%d meta mark set %s accept\n", port, tproxyMark)
	} else {
		fmt.Fprintf(&b, "\t\tmeta l4proto { tcp, udp } th dport 53 redirect to :%d\n", port)
	}
	b.WriteString("\t}\n}\n")

	script := fmt.Sprintf(`#!/bin/sh
# generated by dnsjos: install the DNS redirect rules.
set -eu
nft delete table inet %s 2>/dev/null || true
exec nft -f %s
`, tableName, NFTFile)
	cleanup := fmt.Sprintf(`#!/bin/sh
# generated by dnsjos: remove the DNS redirect rules.
nft delete table inet %s 2>/dev/null || true
`, tableName)
	if tproxy {
		rpApply, rpCleanup := "", ""
		if tp.DisableRPFilter {
			rpApply, rpCleanup = rpFilterScripts(tp.Interfaces)
		}
		script = fmt.Sprintf(`#!/bin/sh
# generated by dnsjos: install TPROXY policy routing and rules.
set -eu
%s
nft delete table inet %s 2>/dev/null || true
ip rule del fwmark %s/0xffffffff lookup %s priority %s 2>/dev/null || true
ip -6 rule del fwmark %s/0xffffffff lookup %s priority %s 2>/dev/null || true
ip route flush table %s 2>/dev/null || true
ip -6 route flush table %s 2>/dev/null || true
ip rule add fwmark %s/0xffffffff lookup %s priority %s
ip route add local 0.0.0.0/0 dev lo table %s
ip -6 rule add fwmark %s/0xffffffff lookup %s priority %s 2>/dev/null || true
ip -6 route add local ::/0 dev lo table %s 2>/dev/null || true
exec nft -f %s
`, rpApply, tableName, tproxyMark, tproxyTable, tproxyPrio, tproxyMark, tproxyTable, tproxyPrio,
			tproxyTable, tproxyTable, tproxyMark, tproxyTable, tproxyPrio, tproxyTable,
			tproxyMark, tproxyTable, tproxyPrio, tproxyTable, NFTFile)
		cleanup = fmt.Sprintf(`#!/bin/sh
# generated by dnsjos: remove TPROXY policy routing and rules.
%s
nft delete table inet %s 2>/dev/null || true
ip rule del fwmark %s/0xffffffff lookup %s priority %s 2>/dev/null || true
ip -6 rule del fwmark %s/0xffffffff lookup %s priority %s 2>/dev/null || true
ip route flush table %s 2>/dev/null || true
ip -6 route flush table %s 2>/dev/null || true
`, rpCleanup, tableName, tproxyMark, tproxyTable, tproxyPrio, tproxyMark, tproxyTable, tproxyPrio,
			tproxyTable, tproxyTable)
	}

	unit := fmt.Sprintf(`[Unit]
Description=DnsJos DNS redirect (TProxy mode)
Documentation=https://github.com/billyriantono/dnsjos
After=network-online.target%s
Wants=network-online.target
%s
[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=%s
ExecStop=%s

[Install]
WantedBy=multi-user.target
`, afterRelay(tproxy), requiresRelay(tproxy), ScriptPath, CleanupPath)

	var relayUnit []byte
	if tproxy {
		relayUnit = []byte(fmt.Sprintf(`[Unit]
Description=DnsJos TPROXY transparent DNS relay
Documentation=https://github.com/billyriantono/dnsjos
After=network-online.target
Wants=network-online.target
Before=%s

[Service]
Type=simple
ExecStart=%s tproxy-relay --port %d --dnsdist 127.0.0.1:%d
Restart=always
RestartSec=2
LimitNOFILE=65536

[Install]
WantedBy=multi-user.target
`, UnitName, AgentBinary, port, port+1))
	}

	return Files{NFT: []byte(b.String()), Script: []byte(script), Cleanup: []byte(cleanup),
		Unit: []byte(unit), RelayUnit: relayUnit}, nil
}

func afterRelay(tproxy bool) string {
	if !tproxy {
		return ""
	}
	return " " + RelayUnitName
}

func requiresRelay(tproxy bool) string {
	if !tproxy {
		return ""
	}
	return "Requires=" + RelayUnitName
}

// rpFilterScripts disables strict reverse-path filtering and remembers the previous
// values so disabling TProxy restores them. FBF/VRF traffic commonly fails rp_filter.
func rpFilterScripts(ifaces []string) (string, string) {
	state := "/var/lib/dnsjos/dnsjos-tproxy-rpfilter.state"
	files := "for f in /proc/sys/net/ipv4/conf/*/rp_filter; do\n"
	if len(ifaces) > 0 {
		files = "for i in " + strings.Join(ifaces, " ") + "; do\n  f=/proc/sys/net/ipv4/conf/$i/rp_filter\n"
	}
	apply := fmt.Sprintf(`RP_STATE=%s
if [ ! -f "$RP_STATE" ]; then
  : > "$RP_STATE"
  %s    [ -w "$f" ] || continue
    printf '%%s=%%s\n' "$f" "$(cat "$f")" >> "$RP_STATE"
    echo 0 > "$f"
  done
else
  %s    [ -w "$f" ] || continue
    echo 0 > "$f"
  done
fi
`, state, files, files)
	cleanup := fmt.Sprintf(`RP_STATE=%s
if [ -f "$RP_STATE" ]; then
  while IFS='=' read -r f v; do
    [ -w "$f" ] && printf '%%s\n' "$v" > "$f"
  done < "$RP_STATE"
  rm -f "$RP_STATE"
fi
`, state)
	return apply, cleanup
}

// Apply writes and installs the redirect rules. It is idempotent: unchanged files and an
// active service are left alone. When the feature is disabled it removes the rules and
// the unit. A missing nft binary is reported as an error for the heartbeat.
func Apply(ctx context.Context, root string, spec api.ConfigSpec, noSystemd bool, log *slog.Logger) error {
	files, err := Render(spec)
	if err != nil {
		return err
	}
	if !spec.Listen.TProxy.Enabled {
		return remove(ctx, root, noSystemd, log)
	}
	if noSystemd {
		// Test mode: write the files so callers can inspect them; never touch netfilter.
		return writeFiles(root, files)
	}
	if _, err := exec.LookPath("nft"); err != nil {
		return errors.New("tproxy: nft is not installed (apt-get install nftables)")
	}
	if spec.Listen.TProxy.IsTProxy() {
		if _, err := exec.LookPath("ip"); err != nil {
			return errors.New("tproxy: ip is not installed (apt-get install iproute2)")
		}
	}

	changed, err := writeFilesChanged(root, files)
	if err != nil {
		return err
	}
	if changed {
		// The unit must be loaded before enable/restart.
		if err := run(ctx, "systemctl", "daemon-reload"); err != nil {
			return err
		}
	}
	if !spec.Listen.TProxy.IsTProxy() {
		// A previous TPROXY config may have left the relay unit behind.
		_ = run(ctx, "systemctl", "disable", "--now", RelayUnitName)
	}
	if spec.Listen.TProxy.IsTProxy() {
		if changed || !activeUnit(ctx, RelayUnitName) {
			if err := run(ctx, "systemctl", "enable", RelayUnitName); err != nil {
				return err
			}
			if err := run(ctx, "systemctl", "restart", RelayUnitName); err != nil {
				return fmt.Errorf("tproxy: starting the transparent relay: %w", err)
			}
			log.Info("TPROXY relay started", "port", spec.Listen.TProxy.EffectivePort(),
				"dnsdist", fmt.Sprintf("127.0.0.1:%d", spec.Listen.TProxy.EffectivePort()+1))
		}
		if !activeUnit(ctx, RelayUnitName) {
			return errors.New("tproxy: the transparent relay is not running")
		}
	}
	if changed || !active(ctx) {
		if err := run(ctx, "systemctl", "enable", UnitName); err != nil {
			return err
		}
		if err := run(ctx, "systemctl", "restart", UnitName); err != nil {
			log.Error("installing the DNS redirect rules failed", "err", err)
			return err
		}
		log.Info("DNS redirect (TProxy) installed", "mode", spec.Listen.TProxy.EffectiveMode(),
			"port", spec.Listen.TProxy.EffectivePort())
	}
	return nil
}

// remove tears the redirect down. Rules are deleted before the service is stopped so a
// half-removed table cannot blackhole DNS if the unit's ExecStop also fails.
func remove(ctx context.Context, root string, noSystemd bool, log *slog.Logger) error {
	installed := false
	for _, p := range []string{UnitPath, RelayUnitPath, ScriptPath, CleanupPath, NFTFile} {
		if _, err := os.Stat(rootPath(root, p)); err == nil {
			installed = true
			break
		}
	}
	if !installed {
		return nil // never enabled on this node
	}
	if !noSystemd {
		if _, err := os.Stat(rootPath(root, CleanupPath)); err == nil {
			_ = run(ctx, "sh", rootPath(root, CleanupPath))
		} else {
			_ = run(ctx, "nft", "delete", "table", "inet", tableName)
		}
		_ = run(ctx, "systemctl", "disable", "--now", UnitName)
		_ = run(ctx, "systemctl", "disable", "--now", RelayUnitName)
		_ = run(ctx, "systemctl", "daemon-reload")
	}
	for _, p := range []string{UnitPath, RelayUnitPath, ScriptPath, CleanupPath, NFTFile} {
		if err := os.Remove(rootPath(root, p)); err != nil && !os.IsNotExist(err) {
			return err
		}
	}
	log.Info("DNS redirect (TProxy) removed")
	return nil
}

// writeFilesChanged writes all three files, returning whether any content changed.
func writeFilesChanged(root string, files Files) (bool, error) {
	changed := false
	for _, f := range []struct {
		path string
		data []byte
		mode os.FileMode
	}{
		{NFTFile, files.NFT, 0o644},
		{ScriptPath, files.Script, 0o755},
		{CleanupPath, files.Cleanup, 0o755},
		{UnitPath, files.Unit, 0o644},
		{RelayUnitPath, files.RelayUnit, 0o644},
	} {
		p := rootPath(root, f.path)
		if f.data == nil {
			if err := os.Remove(p); err == nil {
				changed = true
			} else if !os.IsNotExist(err) {
				return false, err
			}
			continue
		}
		cur, err := os.ReadFile(p)
		if err == nil && bytes.Equal(cur, f.data) {
			if fi, serr := os.Stat(p); serr == nil && fi.Mode().Perm() != f.mode.Perm() {
				if cerr := os.Chmod(p, f.mode); cerr != nil {
					return false, cerr
				}
				changed = true
			}
			continue
		}
		changed = true
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return false, err
		}
		if err := writeAtomic(p, f.data, f.mode); err != nil {
			return false, err
		}
	}
	return changed, nil
}

func writeFiles(root string, files Files) error {
	_, err := writeFilesChanged(root, files)
	return err
}

func writeAtomic(path string, data []byte, mode os.FileMode) error {
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, mode); err != nil {
		return err
	}
	if err := os.Rename(tmp, path); err != nil {
		os.Remove(tmp)
		return err
	}
	return nil
}

func rootPath(root, p string) string {
	if root == "" {
		return p
	}
	return filepath.Join(root, p)
}

func active(ctx context.Context) bool {
	return activeUnit(ctx, UnitName)
}

func activeUnit(ctx context.Context, name string) bool {
	return exec.CommandContext(ctx, "systemctl", "is-active", "--quiet", name).Run() == nil
}

func run(ctx context.Context, name string, args ...string) error {
	out, err := exec.CommandContext(ctx, name, args...).CombinedOutput()
	if err != nil {
		return fmt.Errorf("%s %s: %w: %s", name, strings.Join(args, " "), err, bytes.TrimSpace(out))
	}
	return nil
}

func parsePrefix(s string) (netip.Prefix, error) {
	if p, err := netip.ParsePrefix(s); err == nil {
		return p.Masked(), nil
	}
	a, err := netip.ParseAddr(s)
	if err != nil || a.Zone() != "" {
		return netip.Prefix{}, fmt.Errorf("%q is not a CIDR", s)
	}
	return netip.PrefixFrom(a, a.BitLen()).Masked(), nil
}
